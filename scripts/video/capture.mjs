import { chromium } from "playwright";
const D = "scripts/video/shots";
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
const p = await ctx.newPage();
const vp = (n) => p.screenshot({ path: `${D}/${n}.png` });
const full = (n) => p.screenshot({ path: `${D}/${n}.png`, fullPage: true });
await p.goto("http://localhost:5173/"); await p.waitForTimeout(600);
await vp("01-landing");
await p.getByRole("button", { name: /Experimentar com dados fictícios/ }).click(); await p.waitForURL("**/app"); await p.waitForTimeout(700);
await vp("02-home");
await p.getByRole("link", { name: /Fotografar notinhas/ }).click(); await p.waitForTimeout(600);
await vp("03-capture-empty");
await p.getByRole("button", { name: /Usar fotos de exemplo/ }).click();
await p.getByRole("button", { name: /Ler notinhas \(2 fotos\)/ }).waitFor({ timeout: 20000 }); await p.waitForTimeout(500);
await p.evaluate(() => window.scrollTo(0, 260)); await p.waitForTimeout(300);
await vp("04-capture-photos");
await p.getByRole("button", { name: /Ler notinhas/ }).click();
await p.waitForURL("**/processando"); await p.waitForTimeout(1300);
await vp("05-processing-mid");
await p.getByText(/pedidos encontrados/).waitFor({ timeout: 20000 }); await p.waitForTimeout(250);
await vp("06-processing-done");
await p.waitForURL("**/enderecos", { timeout: 30000 }); await p.waitForTimeout(700);
await vp("07-review");
await p.getByRole("button", { name: /Pedido #2045/ }).click(); await p.getByRole("dialog").waitFor(); await p.waitForTimeout(400);
await vp("08-editor");
await p.getByRole("button", { name: "Ver na foto" }).click(); await p.waitForTimeout(1200);
await vp("09-photo-zoom");
await p.keyboard.press("Escape"); await p.waitForTimeout(300);
await p.getByRole("button", { name: /Ajustar no mapa/ }).click();
const box = await p.getByRole("img", { name: /Ajuste do local/ }).boundingBox();
await p.mouse.click(box.x + box.width * 0.6, box.y + box.height * 0.65); await p.waitForTimeout(300);
await vp("10-pin");
await p.getByRole("button", { name: "Usar este ponto" }).click(); await p.waitForTimeout(500);
await p.keyboard.press("Escape"); await p.waitForTimeout(300);
await p.locator("li", { hasText: "Possível pedido repetido" }).getByRole("button").click();
await p.getByRole("button", { name: "Retirar repetido" }).click(); await p.waitForTimeout(700);
await vp("11-review-resolved");
await p.getByRole("button", { name: /^Organizar rota$/ }).click(); await p.waitForTimeout(400);
await vp("12-origin");
await p.getByRole("button", { name: "Calcular rota" }).click(); await p.waitForURL("**/rota"); await p.waitForTimeout(900);
await full("13-route-full");
await vp("13b-route-top");
await p.getByRole("button", { name: /Iniciar entregas/ }).click(); await p.waitForURL("**/entrega"); await p.waitForTimeout(800);
await vp("14-delivery");
await p.getByRole("button", { name: /^Entregue$/ }).click(); await p.waitForTimeout(500);
await vp("15-delivery-1");
for (let i = 0; i < 6; i++) { await p.getByRole("button", { name: /^Entregue$/ }).click(); await p.waitForTimeout(150); }
await p.waitForTimeout(600);
await vp("16-done");
await p.getByRole("button", { name: "Encerrar saída" }).click(); await p.waitForURL("**/resumo"); await p.waitForTimeout(800);
await full("17-summary");
// desktop
const dctx = await b.newContext({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1.5 });
const d = await dctx.newPage();
await d.goto("http://localhost:5173/"); await d.waitForTimeout(500);
await d.screenshot({ path: `${D}/20-landing-desktop.png` });
await d.getByRole("button", { name: /Experimentar com dados fictícios/ }).click(); await d.waitForURL("**/app"); await d.waitForTimeout(900);
await d.screenshot({ path: `${D}/21-board-desktop.png` });
const seeded = await d.evaluate(() => JSON.parse(localStorage.getItem("rp:demo:v1")).batches.find((x) => x.status === "in_progress").id);
await d.goto(`http://localhost:5173/app/lote/${seeded}/rota`); await d.waitForTimeout(1200);
await d.screenshot({ path: `${D}/22-route-desktop.png` });
await b.close();
console.log("ok");
